export type IconName = keyof typeof icons

export function LucideIcon({ 
  name, 
  className 
}: { 
  name: string, 
  className?: string 
}) {
  const Icon = icons[name as IconName]
  if (!Icon) return null
  return <Icon className={className} />
}
